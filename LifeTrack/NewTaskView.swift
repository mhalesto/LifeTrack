                        guard newValue != nil else { return }
                        withAnimation(.easeOut(duration: 0.28)) {
                            scrollProxy.scrollTo(NewTaskViewAnchor.taskCard, anchor: .top)
                        }
                        documentScrollRequest = nil
                    }
                }
            }
