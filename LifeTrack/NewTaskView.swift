import SwiftData
import SwiftUI
import UniformTypeIdentifiers
import VisionKit

struct NewTaskView: View {
    @Environment(\.dismiss) private var dismiss
    @Environment(\.modelContext) private var modelContext
    @Query(sort: \CustomTaskCategory.title) private var customCategories: [CustomTaskCategory]

    @StateObject private var voiceInput = VoiceTaskInputManager()
    @StateObject private var voiceEnhancer = AIVoiceTaskEnhancer()

    private let existingTask: LifeTask?
    private let originalDocumentStorageName: String?
    private let autoStartVoice: Bool
    private let isFreshNewTask: Bool
    @State private var didAutoStartVoice = false
    @State private var isShowingResumePrompt = false
    @State private var pendingDraft: NewTaskDraft?
    @State private var didOfferDraftResume = false

    @State private var form: NewTaskFormState
    @State private var isImportingDocument = false
    @State private var isScanningDocument = false
    @State private var isAnalyzingDocument = false
    @State private var isShowingCategoryManager = false
    @State private var activeDueDatePicker: DueDatePickerMode?
    @State private var pendingCategoryOption: TaskCategoryOption?
    @State private var documentError: String?
    @State private var didSave = false
    @State private var lastVoiceGeneratedTitle = ""
    @State private var lastVoiceGeneratedNotes = ""
    @State private var didApplyVoiceCategory = false
    @State private var didApplyVoiceDueDate = false
    @State private var didApplyDocumentSuggestion = false
    @State private var documentScrollRequest: UUID?
    @State private var lastAutoGeneratedDocumentNotes = ""
    @State private var isShowingLocationPicker = false
    @State private var isAIEnhancing = false
    @State private var isShowingVoiceTranscriptDisclosure = false
    @AppStorage(LifeTrackSettings.Keys.voiceTranscriptDisclosureShown) private var voiceTranscriptDisclosureShown = false
    @State private var isAdvancedExpanded = false
    @EnvironmentObject private var subscriptionManager: SubscriptionManager

    private static var currentMoneyCurrencyCode: String {
        MoneyCurrency.normalized(UserDefaults.standard.string(forKey: LifeTrackSettings.Keys.moneyCurrencyCode) ?? MoneyCurrency.defaultCode)
    }

    init(task: LifeTask? = nil, template: TaskTemplate? = nil, captureDraft: CapturedTaskDraft? = nil, autoStartVoice: Bool = false) {
        existingTask = task
        originalDocumentStorageName = task?.documentStorageName
        self.autoStartVoice = autoStartVoice
        self.isFreshNewTask = (task == nil && template == nil && captureDraft == nil)
        _form = State(wrappedValue: NewTaskFormState(task: task, template: template, captureDraft: captureDraft))
    }

    var body: some View {
        NavigationStack {
            ZStack {
                LifeTrackTheme.appBackground
                    .ignoresSafeArea()

                ScrollViewReader { scrollProxy in
                    ScrollView {
                        VStack(alignment: .leading, spacing: LifeTrackTheme.Spacing.large) {
                            header

                            voiceCard
                                .id(NewTaskViewAnchor.voiceCard)

                            taskCard
                                .id(NewTaskViewAnchor.taskCard)

                            planningCard

                            TaskDateCard(form: form, activeDueDatePicker: $activeDueDatePicker)

                            financialDetailsCard

                            if subscriptionManager.tier >= .standard {
                                TaskLocationCard(form: form, isShowingLocationPicker: $isShowingLocationPicker)
                            }

                            TaskNotesCard(form: form)

                            advancedFieldsCard

                            documentCard

                        if form.templateAction == .email {
                            templateActionCard
                        }

                        if existingTask != nil {
                            TaskStatusCard(form: form)
                        }
                    }
                        .padding(.horizontal, LifeTrackTheme.Spacing.xLarge)
                        .padding(.top, LifeTrackTheme.Spacing.medium)
                        .padding(.bottom, 112)
                    }
                    .scrollIndicators(.hidden)
                    .onChange(of: documentScrollRequest) { _, newValue in
                        guard newValue != nil else { return }
                        withAnimation(.easeOut(duration: 0.28)) {
                            scrollProxy.scrollTo(NewTaskViewAnchor.taskCard, anchor: .top)
                        }
                        documentScrollRequest = nil
                    }
                    .overlay(alignment: .bottomTrailing) {
                        VoiceFloatingButton(isRecording: voiceInput.isRecording) {
                            handleFloatingVoiceButtonTap(scrollProxy: scrollProxy)
                        }
                        .padding(.trailing, LifeTrackTheme.Spacing.xLarge)
                        .padding(.bottom, LifeTrackTheme.Spacing.xxLarge)
                    }
                }
            }
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel") {
                        dismiss()
                    }
                    .foregroundStyle(LifeTrackTheme.ColorPalette.secondaryText)
                }

                ToolbarItem(placement: .confirmationAction) {
                    Button("Save", action: save)
                        .fontWeight(.semibold)
                        .disabled(!canSave)
                }
            }
            .fileImporter(
                isPresented: $isImportingDocument,
                allowedContentTypes: [.item],
                allowsMultipleSelection: false,
                onCompletion: handleDocumentImport
            )
            .fullScreenCover(isPresented: $isScanningDocument) {
                DocumentScannerView { result in
                    isScanningDocument = false
                    handleScanResult(result)
                }
                .ignoresSafeArea()
            }
            .sheet(isPresented: $isShowingLocationPicker) {
                LocationPickerView { config in
                    form.locationConfig = config
                }
                .presentationDetents([.large])
                .presentationDragIndicator(.visible)
            }
            .sheet(isPresented: $isShowingCategoryManager) {
                CategoryManagerView { option in
                    form.categoryRawValue = option.id
                    pendingCategoryOption = option
                }
                .presentationDetents([.large])
                .presentationDragIndicator(.visible)
            }
            .sheet(item: $activeDueDatePicker) { mode in
                DueDatePickerSheet(mode: mode, dueDate: $form.dueDate)
                    .presentationDetents([mode.presentationDetent])
                    .presentationDragIndicator(.visible)
                    .presentationBackground(LifeTrackTheme.ColorPalette.backgroundBottom)
            }
            .onDisappear {
                voiceInput.stopRecording()

                if !didSave && form.documentStorageName != originalDocumentStorageName {
                    DocumentStore.delete(storageName: form.documentStorageName)
                }

                if isFreshNewTask && !didSave {
                    persistDraftIfMeaningful()
                }
            }
            .onChange(of: voiceInput.transcript) { _, newTranscript in
                form.voiceTranscript = newTranscript
                applyVoiceTranscript(newTranscript)
            }
            .onChange(of: form.dueDate) { _, newDueDate in
                if !form.hasPaymentDate {
                    form.paymentDate = newDueDate
                }
            }
            .onChange(of: voiceInput.isRecording) { wasRecording, isNowRecording in
                if wasRecording && !isNowRecording,
                   !form.voiceTranscript.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                   subscriptionManager.tier >= .ultimate,
                   voiceEnhancer.isConfigured {
                    Task { await enhanceVoiceDraftWithAI() }
                }
            }
            .onAppear {
                if autoStartVoice && !didAutoStartVoice {
                    didAutoStartVoice = true
                    DispatchQueue.main.asyncAfter(deadline: .now() + 0.35) {
                        if !voiceInput.isRecording {
                            voiceInput.toggleRecording()
                        }
                    }
                }

                if isFreshNewTask && !didOfferDraftResume,
                   let draft = NewTaskDraftStore.load() {
                    didOfferDraftResume = true
                    pendingDraft = draft
                    isShowingResumePrompt = true
                }
            }
            .confirmationDialog(
                "Resume previous task?",
                isPresented: $isShowingResumePrompt,
                titleVisibility: .visible,
                presenting: pendingDraft
            ) { draft in
                Button("Resume") {
                    apply(draft: draft)
                    pendingDraft = nil
                }
                Button("Discard", role: .destructive) {
                    NewTaskDraftStore.clear()
                    pendingDraft = nil
                }
                Button("Keep Editing Later", role: .cancel) {
                    pendingDraft = nil
                }
            } message: { draft in
                Text(resumePromptMessage(for: draft))
            }
            .alert("Send voice note to AI?", isPresented: $isShowingVoiceTranscriptDisclosure) {
                Button("Not now", role: .cancel) { }
                Button("Allow") {
                    voiceTranscriptDisclosureShown = true
                    Task { await enhanceVoiceDraftWithAI() }
                }
            } message: {
                Text("To turn your voice note into a structured task, the transcript is sent to Anthropic's Claude API. Avoid speaking sensitive details (full names, addresses, ID numbers, medical info) you don't want to leave the device.")
            }
        }
    }

    private func resumePromptMessage(for draft: NewTaskDraft) -> String {
        let trimmedTitle = draft.title.trimmingCharacters(in: .whitespacesAndNewlines)
        let preview: String
        if !trimmedTitle.isEmpty {
            preview = "\"\(trimmedTitle)\""
        } else if !draft.voiceTranscript.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            preview = "your voice note"
        } else {
            preview = "your unfinished task"
        }
        let relative = draft.savedAt.formatted(.relative(presentation: .named))
        return "You have an unsaved task (\(preview)) from \(relative). Pick up where you left off?"
    }

    private func sanitizedAdvancedFields() -> [String: String] {
        let allowedKeys = Set(selectedCategory.advancedFields.map(\.rawValue))
        var result: [String: String] = [:]
        for (key, value) in form.advancedFieldValues where allowedKeys.contains(key) {
            let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty { result[key] = trimmed }
        }
        return result
    }

    private func currentDraftSnapshot() -> NewTaskDraft {
        NewTaskDraft(
            title: form.title,
            notes: form.notes,
            categoryRawValue: form.categoryRawValue,
            dueDate: form.dueDate,
            priorityRawValue: form.priority.rawValue,
            recurrenceRawValue: form.recurrence.rawValue,
            templateActionRawValue: form.templateAction.rawValue,
            durationMinutes: form.durationMinutes,
            voiceTranscript: form.voiceTranscript,
            locationName: form.locationConfig?.name,
            locationLatitude: form.locationConfig?.latitude,
            locationLongitude: form.locationConfig?.longitude,
            locationRadius: form.locationConfig?.radius,
            locationOnArrival: form.locationConfig?.onArrival,
            advancedFields: sanitizedAdvancedFields(),
            financialEnabled: form.financialEnabled,
            financialTypeRawValue: form.financialType.rawValue,
            plannedAmountText: form.plannedAmountText,
            actualAmountText: form.actualAmountText,
            currencyCode: form.currencyCode,
            budgetCategory: form.budgetCategory,
            hasPaymentDate: form.hasPaymentDate,
            paymentDate: form.hasPaymentDate ? form.paymentDate : nil,
            financialLinkRawValue: form.financialLinkOption.rawValue,
            financialNotes: form.financialNotes,
            includeInMonthlySpending: form.includeInMonthlySpending,
            markPlannedOnCreate: form.markPlannedOnCreate,
            savedAt: Date()
        )
    }

    private func draftHasContent() -> Bool {
        if !form.title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return true }
        if !form.notes.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return true }
        if !form.voiceTranscript.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return true }
        if form.locationConfig != nil { return true }
        if form.priority != .normal { return true }
        if form.recurrence != .none { return true }
        if !sanitizedAdvancedFields().isEmpty { return true }
        if form.financialEnabled { return true }
        return false
    }

    private func persistDraftIfMeaningful() {
        guard draftHasContent() else {
            NewTaskDraftStore.clear()
            return
        }
        NewTaskDraftStore.save(currentDraftSnapshot())
    }

    private func apply(draft: NewTaskDraft) {
        form.title = draft.title
        form.notes = draft.notes
        form.categoryRawValue = draft.categoryRawValue
        form.dueDate = draft.dueDate
        form.priority = TaskPriority(rawValue: draft.priorityRawValue) ?? .normal
        form.recurrence = TaskRecurrence(rawValue: draft.recurrenceRawValue) ?? .none
        form.templateAction = TaskTemplateAction(rawValue: draft.templateActionRawValue) ?? .none
        form.durationMinutes = draft.durationMinutes
        form.voiceTranscript = draft.voiceTranscript
        if let name = draft.locationName,
           let lat = draft.locationLatitude,
           let lon = draft.locationLongitude {
            form.locationConfig = LocationReminderConfig(
                name: name,
                latitude: lat,
                longitude: lon,
                radius: draft.locationRadius ?? 150,
                onArrival: draft.locationOnArrival ?? true
            )
        }
        form.advancedFieldValues = draft.advancedFields
        isAdvancedExpanded = !draft.advancedFields.isEmpty
        form.financialEnabled = draft.financialEnabled ?? false
        form.financialType = TaskFinancialType(rawValue: draft.financialTypeRawValue ?? "") ?? .expense
        form.plannedAmountText = draft.plannedAmountText ?? ""
        form.actualAmountText = draft.actualAmountText ?? ""
        form.currencyCode = MoneyCurrency.normalized(draft.currencyCode ?? MoneyCurrency.defaultCode)
        form.budgetCategory = draft.budgetCategory ?? ""
        form.hasPaymentDate = draft.hasPaymentDate ?? false
        form.paymentDate = draft.paymentDate ?? form.dueDate
        form.financialLinkOption = MoneyLinkOption(rawValue: draft.financialLinkRawValue ?? "") ?? .none
        form.financialNotes = draft.financialNotes ?? ""
        form.includeInMonthlySpending = draft.includeInMonthlySpending ?? true
        form.markPlannedOnCreate = draft.markPlannedOnCreate ?? false
    }

