                DueDatePickerSheet(mode: mode, dueDate: $dueDate)
                    .presentationDetents([mode.presentationDetent])
                    .presentationDragIndicator(.visible)
                    .presentationBackground(LifeTrackTheme.ColorPalette.backgroundBottom)
            }
            .onDisappear {
                voiceInput.stopRecording()

                if !didSave && documentStorageName != originalDocumentStorageName {
                    DocumentStore.delete(storageName: documentStorageName)
                }
            }
            .onChange(of: voiceInput.transcript) { _, newTranscript in
                voiceTranscript = newTranscript
                applyVoiceTranscript(newTranscript)
            }
            .onAppear {
                if autoStartVoice && !didAutoStartVoice {
                    didAutoStartVoice = true
                    DispatchQueue.main.asyncAfter(deadline: .now() + 0.35) {
                        if !voiceInput.isRecording {
                            voiceInput.toggleRecording()
                        }
                    }
                }
            }
        }
    }

