    private var canSave: Bool {
        !form.title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    private var categoryOptions: [TaskCategoryOption] {
        TaskCategoryOption.all(customCategories: customCategories)
    }

    private var selectedCategoryOption: TaskCategoryOption {
        if let pendingCategoryOption, pendingCategoryOption.id == form.categoryRawValue {
            return pendingCategoryOption
        }

        return TaskCategoryOption.resolved(rawValue: form.categoryRawValue, customCategories: customCategories)
    }

    private func removeDocument() {
        if form.documentStorageName != originalDocumentStorageName {
            DocumentStore.delete(storageName: form.documentStorageName)
        }
        form.documentStorageName = nil
        form.documentDisplayName = nil
        clearDocumentAnalysis()

        if form.notes == lastAutoGeneratedDocumentNotes {
            form.notes = ""
        }
        lastAutoGeneratedDocumentNotes = ""
    }

    private func handleScanResult(_ result: Result<URL, Error>) {
        switch result {
        case .success(let url):
            defer { try? FileManager.default.removeItem(at: url) }

            do {
                let pendingDocumentStorageName = form.documentStorageName
                let storedDocument = try DocumentStore.saveSecurityScopedFile(from: url)
                if pendingDocumentStorageName != originalDocumentStorageName {
                    DocumentStore.delete(storageName: pendingDocumentStorageName)
                }
                form.documentStorageName = storedDocument.storageName
                form.documentDisplayName = storedDocument.displayName
                documentError = nil
                analyzeDocument(storageName: storedDocument.storageName, displayName: storedDocument.displayName)
                LifeTrackHaptics.lightImpact()
            } catch {
                documentError = "Scan could not be saved."
                isAnalyzingDocument = false
            }
        case .failure(let error):
            if case DocumentScannerView.ScanError.cancelled = error {
                return
            }
            documentError = "Scan could not be completed."
            isAnalyzingDocument = false
        }
    }

    private func handleDocumentImport(_ result: Result<[URL], Error>) {
        switch result {
        case .success(let urls):
            guard let url = urls.first else {
                return
            }

            do {
                let pendingDocumentStorageName = form.documentStorageName
                let storedDocument = try DocumentStore.saveSecurityScopedFile(from: url)
                if pendingDocumentStorageName != originalDocumentStorageName {
                    DocumentStore.delete(storageName: pendingDocumentStorageName)
                }
                form.documentStorageName = storedDocument.storageName
                form.documentDisplayName = storedDocument.displayName
                documentError = nil
                analyzeDocument(storageName: storedDocument.storageName, displayName: storedDocument.displayName)
            } catch {
                documentError = "Document could not be attached."
                isAnalyzingDocument = false
            }
        case .failure:
            documentError = "Document could not be attached."
            isAnalyzingDocument = false
        }
    }

    private func analyzeDocument(storageName: String, displayName: String) {
        guard let url = DocumentStore.url(for: storageName) else {
            clearDocumentAnalysis()
            documentError = "Document was attached, but could not be read yet."
            return
        }

        clearDocumentAnalysis()
        isAnalyzingDocument = true

        Task {
            let result = await DocumentAnalysisManager.analyze(url: url, displayName: displayName)
            await MainActor.run {
                guard form.documentStorageName == storageName else {
                    return
                }

                form.documentExtractedText = result.extractedText
                form.documentAnalysisSummary = result.summary
                form.documentSuggestedTitle = result.suggestedTitle
                form.documentSuggestedDueDate = result.suggestedDueDate
                form.documentKeywords = result.keywords
                isAnalyzingDocument = false

                applyAutoGeneratedDocumentNotes(displayName: displayName, result: result)
            }
        }
    }

    private func applyAutoGeneratedDocumentNotes(displayName: String, result: DocumentAnalysisResult) {
        let autoNotes = buildAutoDocumentNotes(displayName: displayName, result: result)
        guard !autoNotes.isEmpty else { return }

        let trimmed = form.notes.trimmingCharacters(in: .whitespacesAndNewlines)

        if trimmed.isEmpty || form.notes == lastAutoGeneratedDocumentNotes {
            form.notes = autoNotes
            lastAutoGeneratedDocumentNotes = autoNotes
        }
    }

    private func buildAutoDocumentNotes(displayName: String, result: DocumentAnalysisResult) -> String {
        var lines: [String] = ["Attached: \(displayName)"]

        if !result.keywords.isEmpty {
            lines.append("Detected: \(result.keywords.prefix(5).joined(separator: ", "))")
        }

        if let suggestedDueDate = result.suggestedDueDate {
            lines.append("Date found: \(suggestedDueDate.weekdayDateString)")
        }

        let excerpt = documentExcerpt(from: result.extractedText)
        if !excerpt.isEmpty {
            lines.append("")
            lines.append(excerpt)
        }

        return lines.joined(separator: "\n")
    }

    private func documentExcerpt(from text: String) -> String {
        let normalized = text
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard !normalized.isEmpty else { return "" }

        let maxLength = 240
        if normalized.count <= maxLength {
            return normalized
        }

        let clipped = normalized.prefix(maxLength)
        if let lastSpace = clipped.lastIndex(of: " ") {
            return clipped[..<lastSpace] + "…"
        }

        return clipped + "…"
    }

    private func clearDocumentAnalysis() {
        form.documentExtractedText = ""
        form.documentAnalysisSummary = nil
        form.documentSuggestedTitle = nil
        form.documentSuggestedDueDate = nil
        form.documentKeywords = []
        didApplyDocumentSuggestion = false
    }

    private var hasDocumentAnalysis: Bool {
        form.documentAnalysisSummary != nil ||
            form.documentSuggestedTitle != nil ||
            form.documentSuggestedDueDate != nil ||
            !form.documentKeywords.isEmpty ||
            !form.documentExtractedText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    private func applyDocumentSuggestion() {
        var didChange = false

        if let suggestedTitle = form.documentSuggestedTitle, !suggestedTitle.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            withAnimation(.easeOut(duration: 0.2)) {
                form.title = suggestedTitle
            }
            didChange = true
        }

        if let suggestedDueDate = form.documentSuggestedDueDate {
            withAnimation(.easeOut(duration: 0.2)) {
                form.dueDate = suggestedDueDate
            }
            didChange = true
        }

        if form.documentKeywords.contains("insurance") || form.documentKeywords.contains("invoice") || form.documentKeywords.contains("bill") || form.documentKeywords.contains("tax") {
            form.categoryRawValue = TaskCategory.finance.rawValue
            pendingCategoryOption = nil
            didChange = true
        } else if form.documentKeywords.contains("appointment") || form.documentKeywords.contains("medical") {
            form.categoryRawValue = TaskCategory.health.rawValue
            pendingCategoryOption = nil
            didChange = true
        } else if form.documentKeywords.contains("school") || form.documentKeywords.contains("application") {
            form.categoryRawValue = TaskCategory.personal.rawValue
            pendingCategoryOption = nil
            didChange = true
        }

        if didChange {
            LifeTrackHaptics.lightImpact()
            withAnimation(.easeOut(duration: 0.22)) {
                didApplyDocumentSuggestion = true
            }
            documentScrollRequest = UUID()
        }
    }

    private func applyVoiceTranscript(_ transcript: String, force: Bool = false) {
        let cleanedTranscript = transcript.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanedTranscript.isEmpty else {
            return
        }

        let draft = VoiceTaskParser.parse(cleanedTranscript)

        if let draftTitle = draft.title, force || form.title.isEmpty || form.title == lastVoiceGeneratedTitle {
            form.title = draftTitle
            lastVoiceGeneratedTitle = draftTitle
        }

        if let draftCategory = draft.category, force || !didApplyVoiceCategory {
            form.categoryRawValue = draftCategory.rawValue
            pendingCategoryOption = nil
            didApplyVoiceCategory = true
        }

        if let draftDueDate = draft.dueDate, force || !didApplyVoiceDueDate {
            form.dueDate = draftDueDate
            didApplyVoiceDueDate = true
        }

        let trimmedNotes = form.notes.trimmingCharacters(in: .whitespacesAndNewlines)
        let notesIsOverridableByVoice =
            trimmedNotes.isEmpty ||
            form.notes == lastVoiceGeneratedNotes ||
            (trimmedNotes == lastAutoGeneratedDocumentNotes.trimmingCharacters(in: .whitespacesAndNewlines) && !lastAutoGeneratedDocumentNotes.isEmpty)

        if let draftNotes = draft.notes, !draftNotes.isEmpty, force || notesIsOverridableByVoice {
            form.notes = draftNotes
            lastVoiceGeneratedNotes = draftNotes
        } else if draft.notes == nil, form.notes == lastVoiceGeneratedNotes, !lastVoiceGeneratedNotes.isEmpty {
            form.notes = ""
            lastVoiceGeneratedNotes = ""
        }

        if let draftPriority = draft.priority, force {
            form.priority = draftPriority
        }

        applyFinancialDraft(draft, force: force)
    }

    private func applyFinancialDraft(_ draft: VoiceTaskDraft, force: Bool) {
        let hasFinancialValues =
            draft.financialEnabled == true ||
            draft.financialType != nil ||
            draft.plannedAmount != nil ||
            draft.actualAmount != nil ||
            draft.currencyCode != nil ||
            draft.budgetCategory != nil ||
            draft.paymentDate != nil ||
            draft.linkedBudgetId != nil ||
            draft.linkedGoalId != nil ||
            draft.includeInMonthlySpending != nil ||
            draft.markPlannedOnCreate != nil ||
            draft.financialNotes != nil

        guard hasFinancialValues else { return }

        let wasFinancialEnabled = form.financialEnabled
        if force || !form.financialEnabled || draft.financialEnabled == true {
            form.financialEnabled = true
        }

        if let draftType = draft.financialType, force || !wasFinancialEnabled {
            form.financialType = draftType
        }

        if let plannedAmount = draft.plannedAmount,
           force || form.plannedAmountText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            form.plannedAmountText = Self.amountInputString(plannedAmount)
        }

        if let actualAmount = draft.actualAmount,
           force || form.actualAmountText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            form.actualAmountText = Self.amountInputString(actualAmount)
        }

        if draft.currencyCode != nil,
           force || form.currencyCode == MoneyCurrency.defaultCode {
            form.currencyCode = Self.currentMoneyCurrencyCode
        }

        if let draftBudgetCategory = draft.budgetCategory,
           force || form.budgetCategory.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            form.budgetCategory = draftBudgetCategory
        }

        if let draftPaymentDate = draft.paymentDate, force || !form.hasPaymentDate {
            form.paymentDate = draftPaymentDate
            form.hasPaymentDate = true
        }

        if (draft.linkedBudgetId != nil || draft.linkedGoalId != nil), force || !wasFinancialEnabled {
            form.financialLinkOption = MoneyLinkOption.resolved(
                budgetId: draft.linkedBudgetId,
                goalId: draft.linkedGoalId
            )
        }

        if let include = draft.includeInMonthlySpending, force || !wasFinancialEnabled {
            form.includeInMonthlySpending = include
        }

        if let markPlanned = draft.markPlannedOnCreate, force || !wasFinancialEnabled {
            form.markPlannedOnCreate = markPlanned
        }

        if let draftNotes = draft.financialNotes,
           force || form.financialNotes.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            form.financialNotes = draftNotes
        }
    }

    private func enhanceVoiceDraftWithAI() async {
        if !voiceTranscriptDisclosureShown {
            await MainActor.run { isShowingVoiceTranscriptDisclosure = true }
            return
        }

        isAIEnhancing = true
        defer { isAIEnhancing = false }

        guard let enhanced = await voiceEnhancer.enhance(transcript: form.voiceTranscript) else { return }

        withAnimation(.easeOut(duration: 0.22)) {
            applyVoiceTranscript(form.voiceTranscript, force: false)

            if let t = enhanced.title, !t.isEmpty {
                form.title = t
                lastVoiceGeneratedTitle = t
            }

            if let n = enhanced.notes, !n.isEmpty {
                form.notes = n
                lastVoiceGeneratedNotes = n
            }

            if let d = enhanced.dueDate {
                form.dueDate = d
                didApplyVoiceDueDate = true
            }

            if let cat = enhanced.category {
                form.categoryRawValue = cat.rawValue
                didApplyVoiceCategory = true
            }

            if let pri = enhanced.priority {
                form.priority = pri
            }

            if !enhanced.advancedFields.isEmpty {
                let allowedKeys = Set(selectedCategory.advancedFields.map(\.rawValue))
                for (key, value) in enhanced.advancedFields where allowedKeys.contains(key) {
                    let existing = form.advancedFieldValues[key]?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
                    if existing.isEmpty {
                        form.advancedFieldValues[key] = value
                    }
                }
                if !form.advancedFieldValues.isEmpty {
                    isAdvancedExpanded = true
                }
            }

            applyFinancialDraft(enhanced, force: false)
        }
    }

    private func save() {
        let cleanedTitle = form.title.trimmingCharacters(in: .whitespacesAndNewlines)
        let now = Date()
        let wasCompleted = existingTask?.isCompleted ?? false

        let task: LifeTask
        if let existingTask {
            task = existingTask
            if originalDocumentStorageName != form.documentStorageName {
                DocumentStore.delete(storageName: originalDocumentStorageName)
            }
            task.title = cleanedTitle
            task.categoryRawValue = form.categoryRawValue
            task.dueDate = form.dueDate
            task.isCompleted = form.isCompleted
            task.notes = form.notes
            task.templateAction = form.templateAction
            task.priority = form.priority
            task.recurrence = form.recurrence
            task.scheduledDurationMinutes = form.durationMinutes
            task.documentStorageName = form.documentStorageName
            task.documentDisplayName = form.documentDisplayName
            task.documentExtractedText = form.documentExtractedText
            task.documentAnalysisSummary = form.documentAnalysisSummary
            task.documentSuggestedTitle = form.documentSuggestedTitle
            task.documentSuggestedDueDate = form.documentSuggestedDueDate
            task.documentKeywords = form.documentKeywords
            task.locationReminderName = form.locationConfig?.name
            task.locationReminderLatitude = form.locationConfig?.latitude
            task.locationReminderLongitude = form.locationConfig?.longitude
            task.locationReminderRadius = form.locationConfig?.radius
            task.locationReminderOnArrival = form.locationConfig?.onArrival ?? true
            task.advancedFields = sanitizedAdvancedFields()
            applyFinancialDetails(to: task)
            task.updatedAt = now
        } else {
            task = LifeTask(
                title: cleanedTitle,
                category: selectedCategory,
                categoryRawValue: form.categoryRawValue,
                dueDate: form.dueDate,
                isCompleted: form.isCompleted,
                notes: form.notes,
                templateAction: form.templateAction,
                priority: form.priority,
                recurrence: form.recurrence,
                estimatedDurationMinutes: form.durationMinutes,
                documentStorageName: form.documentStorageName,
                documentDisplayName: form.documentDisplayName,
                documentExtractedText: form.documentExtractedText,
                documentAnalysisSummary: form.documentAnalysisSummary,
                documentSuggestedTitle: form.documentSuggestedTitle,
                documentSuggestedDueDate: form.documentSuggestedDueDate,
                documentKeywords: form.documentKeywords,
                createdAt: now,
                updatedAt: now
            )
            task.locationReminderName = form.locationConfig?.name
            task.locationReminderLatitude = form.locationConfig?.latitude
            task.locationReminderLongitude = form.locationConfig?.longitude
            task.locationReminderRadius = form.locationConfig?.radius
            task.locationReminderOnArrival = form.locationConfig?.onArrival ?? true
            task.advancedFields = sanitizedAdvancedFields()
            applyFinancialDetails(to: task)
            if task.isHabit { task.habitGroupID = task.id }
            modelContext.insert(task)
        }

        let nextRecurringTask: LifeTask?
        if !wasCompleted && task.isCompleted {
            nextRecurringTask = task.nextRecurringTask(completedAt: now)
            if let nextRecurringTask {
                modelContext.insert(nextRecurringTask)
            }
        } else {
            nextRecurringTask = nil
        }

        try? modelContext.save()
        ReminderScheduler.synchronizeReminder(
            taskID: task.id,
            title: task.title,
            categoryTitle: selectedCategoryOption.title,
            dueDate: task.dueDate,
            isCompleted: task.isCompleted,
            isHighPriority: task.priority == .high,
            detailLine: task.reminderDetailLine(categoryTitle: selectedCategoryOption.title)
        )
        if let nextRecurringTask {
            TaskLifecycleManager.synchronizeReminder(
                for: nextRecurringTask,
                customCategories: customCategories
            )
        }
        LocationReminderManager.shared.cancelRegion(for: task.id)
        if task.hasLocationReminder && !task.isCompleted {
            LocationReminderManager.shared.scheduleRegion(for: task)
        }
        didSave = true
        if isFreshNewTask {
            NewTaskDraftStore.clear()
        }
        dismiss()
    }

    private func applyFinancialDetails(to task: LifeTask) {
        task.financialEnabled = form.financialEnabled
        task.financialType = form.financialType
        task.plannedAmount = form.financialEnabled ? parseAmount(form.plannedAmountText) : 0
        let actual = parseAmount(form.actualAmountText)
        task.actualAmount = form.financialEnabled && actual > 0 ? actual : nil
        task.currencyCode = MoneyCurrency.normalized(form.currencyCode)
        task.budgetCategory = form.financialEnabled ? form.budgetCategory.trimmingCharacters(in: .whitespacesAndNewlines) : ""
        task.paymentDate = form.financialEnabled && form.hasPaymentDate ? form.paymentDate : nil
        task.linkedBudgetId = form.financialEnabled ? form.financialLinkOption.budgetId : nil
        task.linkedGoalId = form.financialEnabled ? form.financialLinkOption.goalId : nil
        task.includeInMonthlySpending = form.includeInMonthlySpending
        task.markPlannedOnCreate = form.markPlannedOnCreate
        task.financialNotes = form.financialEnabled ? form.financialNotes : ""
    }

    private func parseAmount(_ value: String) -> Double {
        let normalized = value
            .replacingOccurrences(of: ",", with: ".")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return Double(normalized) ?? 0
    }

    private static func amountInputString(_ amount: Double?) -> String {
        guard let amount, amount > 0 else { return "" }
        if amount.rounded(.down) == amount {
            return String(Int(amount))
        }
        return String(format: "%.2f", amount)
    }

    private var selectedCategory: TaskCategory {
        TaskCategory(rawValue: form.categoryRawValue) ?? .other
    }

